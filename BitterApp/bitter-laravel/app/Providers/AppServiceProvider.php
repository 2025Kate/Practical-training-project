<?php

namespace App\Providers;

use Illuminate\Support\ServiceProvider;

/**
 * AppServiceProvider - основной сервис-провайдер приложения.
 * 
 * Сервис-провайдеры в Laravel являются центральным местом для регистрации
 * привязок контейнера, сервисов и другой начальной загрузки приложения.
 * 
 * Этот провайдер регистрирует кастомные сервисы приложения в контейнере
 * внедрения зависимостей.
 */
class AppServiceProvider extends ServiceProvider
{
    /**
     * Регистрация любых сервисов приложения.
     * 
     * Этот метод вызывается когда все сервис-провайдеры были зарегистрированы
     * но еще не произошла загрузка сервисов. Здесь регистрируются привязки
     * в контейнере внедрения зависимостей.
     * 
     * @return void
     */
    public function register(): void
    {
        // Регистрация PostService в контейнере внедрения зависимостей
        // При запросе PostService будет возвращен новый экземпляр класса
        $this->app->bind(PostService::class, function ($app) {
            return new PostService();
        });
        
        // Регистрация UserService в контейнере внедрения зависимостей
        // При запросе UserService будет возвращен новый экземпляр класса
        $this->app->bind(UserService::class, function ($app) {
            return new UserService();
        });
        
        // Примечание: В Laravel 8+ можно использовать более короткий синтаксис:
        // $this->app->bind(PostService::class);
        // $this->app->bind(UserService::class);
        // Контейнер автоматически разрешит зависимости через рефлексию
    }

    /**
     * Загрузка любых сервисов приложения.
     * 
     * Этот метод вызывается после регистрации всех сервис-провайдеров,
     * что позволяет выполнять инициализацию сервисов, которые зависят
     * от других зарегистрированных сервисов.
     * 
     * Здесь обычно регистрируются:
     * - обработчики событий
     * - middleware
     * - публикация ресурсов
     * - роуты
     * - представления
     * 
     * @return void
     */
    public function boot(): void
    {
        // Метод оставлен пустым, так как в данный момент 
        // не требуется дополнительная загрузка сервисов
        
        // Примеры использования метода boot():
        // - View::composer('view.name', ...);
        // - Event::listen(...);
        // - Route::bind(...);
        // - инициализация сторонних пакетов
    }
}