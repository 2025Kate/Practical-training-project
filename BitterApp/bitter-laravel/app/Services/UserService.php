<?php

namespace App\Services;

use App\Models\User;
use Illuminate\Support\Facades\Log;

/**
 * UserService - сервисный класс для работы с пользователями.
 * 
 * Инкапсулирует бизнес-логику работы с пользователями.
 * Обеспечивает уровень абстракции между контроллерами и моделью User.
 */
class UserService
{
    /**
     * Поиск пользователя по имени пользователя (username).
     * 
     * Этот метод предоставляет единый интерфейс для поиска пользователей
     * по их уникальному имени пользователя. Может быть расширен дополнительной
     * логикой (кеширование, логирование, проверки и т.д.).
     * 
     * @param string $username Имя пользователя для поиска
     * @return User|null Объект пользователя если найден, либо null
     */
    public function findByUsername(string $username): ?User
    {
        // Поиск пользователя по имени пользователя в базе данных
        // Используется метод first() для получения первого совпадения или null
        return User::where('username', $username)->first();
    }
}