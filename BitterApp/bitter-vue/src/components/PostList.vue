<template>
  <!-- 
    Контейнер для списка постов
    Основная задача этого компонента - отображение коллекции постов
  -->
  <div class="posts-container">
    <!-- 
      Цикл v-for для отображения каждого поста через компонент PostItem
      :key="post.id" - обязательный атрибут для идентификации элементов в цикле
      :post="post" - передача объекта поста в дочерний компонент
      
      Проксирование событий от дочерних компонентов:
      @filter-by-author - слушаем событие от PostItem и эмитим его дальше родителю
      @filter-by-hashtag - аналогично для событий хэштегов
      
      $event - содержит данные, переданные из дочернего компонента
      $emit() - отправка события родительскому компоненту
    -->
    <PostItem 
      v-for="post in posts"
      :key="post.id" 
      :post="post"
      @filter-by-author="$emit('filter-by-author', $event)"
      @filter-by-hashtag="$emit('filter-by-hashtag', $event)"
    />
  </div>
</template>

<script>
// Импорт дочернего компонента для отображения отдельных постов
import PostItem from './PostItem.vue';

export default {
  // Регистрация дочерних компонентов
  components: { PostItem },
  
  // Входные параметры (props) - данные, получаемые от родительского компонента
  props: {
    posts: {
      type: Array,       // Ожидаем массив объектов
      required: true     // Обязательный параметр
      // Можно добавить валидацию для более строгой проверки:
      // validator: (value) => {
      //   return Array.isArray(value) && value.every(item => item.id && item.text)
      // }
    }
  },
  
  // Явное объявление событий, которые компонент может генерировать
  // Это улучшает документирование и позволяет Vue валидировать события
  emits: ['filter-by-author', 'filter-by-hashtag']
  
  // Примечание: данный компонент не содержит собственной логики (methods, data)
  // Он служит pure-presentational компонентом - только отображает данные
  // и проксирует события от дочерних компонентов к родителю
}
</script>

