// Импортируем функцию createApp из Vue 3
// createApp создает экземпляр приложения с изоляцией контекста
import { createApp } from 'vue'  // Импортируем createApp

// Импортируем корневой компонент App - основной компонент приложения
// который будет точкой входа для рендеринга
import App from './App.vue'

// Импортируем сконфигурированный экземпляр маршрутизатора (Vue Router)
// который управляет навигацией и отображением компонентов по маршрутам
import router from './router'

// Импортируем сконфигурированное хранилище состояния (Vuex)
// которое управляет глобальным состоянием приложения
import store from './store'

// Создаем экземпляр приложения Vue, передавая корневой компонент App
// Это инициализирует приложение и устанавливает компонент App как корневой
const app = createApp(App)

// Подключаем маршрутизатор к приложению
// Это добавляет:
// - Поддержку навигации по маршрутам
// - Доступ к router и route в компонентах
// - Компоненты <router-link> и <router-view>
app.use(router)

// Подключаем хранилище состояния к приложению
// Это добавляет:
// - Глобальное управление состоянием
// - Доступ к store в компонентах через useStore()
// - Реактивность состояния
app.use(store)

// Монтируем приложение в DOM элемент с id="app"
// Это:
// - Заменяет элемент #app корневым компонентом App
// - Активирует реактивность и рендеринг
// - Запускает процесс отображения приложения
app.mount('#app')

// Процесс инициализации завершен. Приложение теперь:
// 1. Управляет маршрутизацией через Vue Router
// 2. Управляет состоянием через Vuex
// 3. Рендерит компоненты через корневой App.vue
// 4. Реагирует на изменения данных и обновляет UI